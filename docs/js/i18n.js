export function detectDefaultLang() {
  try {
    const saved = localStorage.getItem('stlviewer_lang');
    if (saved === 'tr' || saved === 'en') return saved;
  } catch {}
  if (typeof navigator !== 'undefined' && /^tr\b/i.test(navigator.language || '')) {
    return 'tr';
  }
  return 'tr';
}

export function createTranslator(lang = 'tr') {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return (key) => dict[key] ?? TRANSLATIONS.en[key] ?? key;
}
